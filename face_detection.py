import cv2  # Импортируем библиотеку OpenCV для работы с изображениями
import numpy as np  # Импортируем библиотеку NumPy для работы с массивами
import streamlit as st  # Импортируем Streamlit для создания веб-приложения
from PIL import Image  # Импортируем библиотеку PIL для обработки изображений

# Функция для обнаружения лиц на изображении с использованием каскадов Хаара(Каскад Хаара — это алгоритм для быстрого 
# обнаружения объектов на изображении, например, лиц, глаз, автомобилей. 
# Он основан на поиске характерных шаблонов (признаков) в изображении.)
def detect_faces(image):
    # Преобразуем изображение в формат, который понимает OpenCV (RGB -> массив NumPy)
    img_array = np.array(image.convert('RGB'))#image.convert('RGB') – преобразует изображение в формат RGB (красный, зелёный, синий) с помощью библиотеки Pillow (PIL).
#np.array(...) – превращает изображение в массив NumPy, где:

#Каждый пиксель представлен как массив из трёх значений (R, G, B).

#Размерность массива: (высота, ширина, 3), то есть-трехмерный массив.

#Первая ось (высота) — количество строк пикселей (h).

#Вторая ось (ширина) — количество столбцов пикселей (w).

#Третья ось (3 канала) — цветовые компоненты (R, G, B).

    # Преобразуем изображение в оттенки серого для улучшения производительности, то есть этот код конвертирует
    #  цветное изображение  в чёрно-белое (градиенты серого) ( то есть с BGR в GRAY) с помощью OpenCV.
    gray = cv2.cvtColor(img_array, cv2.COLOR_BGR2GRAY)
    
    # Загружаем предобученный классификатор для обнаружения лиц
    face_cascade = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')

#cv2.CascadeClassifier(...):
#-Создаёт объект каскадного классификатора(Каскадный классификатор — это алгоритм, который распознаёт объекты (например, лица) на изображении поэтапно, через серию "фильтров" или "проверок", начиная с простых и заканчивая сложными.), который может обнаруживать объекты (например, лица).
#-Принимает путь к файлу .xml, который содержит обученные параметры для распознавания объектов.

#cv2.data.haarcascades:
#-Это путь к встроенной папке OpenCV на твоем компьютере, где хранятся предобученные модели для обнаружения различных объектов.

#haarcascade_frontalface_default.xml:
#-Файл .xml содержит готовую модель, которая была обучена на большом наборе изображений с лицами.
#-Это файл каскадного классификатора для распознавания лиц, смотрящих в камеру (фронтальных).
#-Он содержит готовые признаки (patterns), которые описывают, как обычно выглядят лица (глаза, нос, рот и т. д.).


# В результате сложения: cv2.data.haarcascades + 'haarcascade_frontalface_default.xml' получается полный путь
#  к файлу haarcascade_frontalface_default.xml, который хранится в стандартной директории OpenCV.





    # Обнаруживаем лица на изображении с улучшенными параметрами
    faces = face_cascade.detectMultiScale(#detectMultiScale() находит прямоугольные области, где, с высокой вероятностью, находятся лица
        gray,#Это входное изображение в градациях серого.
        scaleFactor=1.1,  # Коэффициент масштабирования изображения. Этот параметр определяет,
         # насколько уменьшается изображение при поиске лиц на каждой итерации поиска(то есть уменьшение а 1.1 раза на каждой итерации).
        minNeighbors=10,  # Минимальное количество соседей для отбора прямоугольников. Этот параметр определяет, сколько прямоугольников (детекторов) должно пересечься, чтобы область считалась лицом.
        minSize=(55, 55),  # Минимальный размер прямоугольника(первая 55 — это ширина (в пикселях),вторая 55 — это высота (в пикселях)). Этот параметр задаёт минимальный размер обнаруживаемого лица (в пикселях). Что он делает? Если лицо меньше 55x55 пикселей, алгоритм игнорирует его.
        flags=cv2.CASCADE_SCALE_IMAGE  # Флаги для метода обнаружения. cv2.CASCADE_SCALE_IMAGE заставляет алгоритм масштабировать изображение, а не фильтр.
    )
    
    # Рисуем прямоугольники вокруг обнаруженных лиц
    for (x, y, w, h) in faces:# faces — это список прямоугольников, где каждое лицо представлено 4 значениями:

#x — координата X верхнего левого угла прямоугольника (лицо начинается отсюда).

#y — координата Y верхнего левого угла.

#w — ширина обнаруженного лица.

#h — высота обнаруженного лица.
# Цикл проходит по всем лицам, найденным в faces, и для каждого извлекает координаты.

        cv2.rectangle(img_array, (x, y), (x+w, y+h), (255, 0, 0), 2)
       # Рисует прямоугольник вокруг каждого лица с помощью cv2.rectangle().

#Разбор аргументов:
# img_array — изображение, на котором рисуем.
# (x, y) — координаты верхнего левого угла прямоугольника (начало лица).
# (x+w, y+h) — координаты нижнего правого угла (где заканчивается лицо).
# (255, 0, 0) — цвет прямоугольника (RGB). (255, 0, 0) — синий.
# 2 — толщина линии прямоугольника (2 пикселя).
    
    # Возвращаем изображение с обведенными лицами и количество обнаруженных лиц
    return img_array, faces

# Интерфейс Streamlit
st.title('Приложение для обнаружения лиц')  # Заголовок приложения
st.write("Загрузите изображение, и приложение обнаружит лица на нём.")  # Инструкция для пользователя

# Загрузка изображения пользователем
uploaded_file = st.file_uploader("Выберите изображение...", type=["jpg", "jpeg", "png"])#добавляет в интерфейс Streamlit виджет для загрузки изображения.
#st.file_uploader() — это виджет загрузки файлов в Streamlit.
#Выберите изображение..." — текст, который видит пользователь.
#type=["jpg", "jpeg", "png"] — ограничение допустимых форматов файлов (только изображения).
#Что делает uploaded_file?
#uploaded_file содержит загруженный файл, если пользователь выбрал изображение.
#Если файл не загружен, то uploaded_file = None.

if uploaded_file is not None:
    # Открываем загруженное изображение
    image = Image.open(uploaded_file)
    # Отображаем загруженное изображение
    st.image(image, caption='Загруженное изображение', use_column_width=True)
    #st.image() — это функция Streamlit для отображения изображений.
    #image — переменная, содержащая загруженное изображение (например, объект PIL.Image).
#caption — подпись под изображением. В данном случае "Загруженное изображение".
#use_column_width=True заставляет изображение масштабироваться по ширине колонки Streamlit.
# Если True, изображение растягивается, чтобы занять всю ширину контейнера в веб-интерфейсе.


    # Обработка изображения и отображение результата
    if st.button('Обнаружить лица'):
#st.button('Обнаружить лица') — создаёт кнопку в интерфейсе Streamlit.
#Когда пользователь нажимает кнопку, код внутри if выполняется.



        # Обнаруживаем лица на изображении
        result_img, faces = detect_faces(image)
        # Отображаем изображение с обведенными лицами
#detect_faces(image) — это функция, которая анализирует изображение и ищет лица.
# Возвращает два значения:
#result_img — изображение с обведёнными прямоугольниками лиц.
#faces — список координат обнаруженных лиц (каждое лицо — это (x, y, w, h)).

        st.image(result_img, caption='Обработанное изображение', use_column_width=True)
        # Сообщаем пользователю количество найденных лиц
        st.success(f"Найдено {len(faces)} лиц(о/а)")
        #len(faces) возвращает число найденных лиц.
